#include <iostream> // Подключаем библиотеку для ввода и вывода
#include <cmath>    // Подключаем библиотеку для функции pow и fabs
using namespace std;

int main()
{
    setlocale(LC_ALL, ".65001"); // Подключаем русский язык в консоли

    double e = 0.0001; // Задаём точность вычислений
    double a = 2.0;    // Первый член ряда: a1 = 2^1 * 1! / 1^1 = 2
    double sum = 0.0;  // Переменная для хранения суммы ряда
    int n = 1;         // Номер текущего члена ряда

    // Пока модуль текущего члена не меньше заданной точности,
    // прибавляем его к сумме и вычисляем следующий член
    while (fabs(a) >= e)
    {
        sum += a; // Добавляем текущий член к сумме

        // Вычисляем следующий член по рекуррентной формуле:
        // a(n+1) = a(n) * 2 * (n / (n + 1))^n
        a = a * 2.0 * pow((double)n / (n + 1), n);

        n++; // Переходим к следующему номеру члена ряда
    }

    // Выводим полученную сумму
    cout << "Сумма ряда = " << sum << endl;

    return 0; // Завершаем программу
}


