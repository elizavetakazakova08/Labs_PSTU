#include <iostream> // Подключаем библиотеку для ввода и вывода
using namespace std; // Используем стандартное пространство имён

// Создаём структуру для хранения комплексного числа
struct Complex
{
    double real; // Действительная часть числа
    double imag; // Мнимая часть числа
};

// Перегруженная функция для сложения целых чисел
int sum(int a, int b)
{
    return a + b; // Возвращаем сумму двух целых чисел
}

// Перегруженная функция для сложения комплексных чисел
Complex sum(Complex a, Complex b)
{
    Complex result; // Создаём переменную для хранения результата

    result.real = a.real + b.real; // Складываем действительные части
    result.imag = a.imag + b.imag; // Складываем мнимые части

    return result; // Возвращаем полученное комплексное число
}

int main()
{
    setlocale(LC_ALL, "Russian"); // Включаем русский язык в консоли

    int a, b; // Объявляем две переменные целого типа

    cout << "Введите два целых числа: ";
    cin >> a >> b; // Вводим целые числа с клавиатуры

    cout << "Сумма целых чисел: " << sum(a, b) << endl;
    // Вызываем первую перегруженную функцию

    Complex c1, c2; // Объявляем два комплексных числа

    cout << "\nВведите действительную и мнимую части первого "
         << "комплексного числа: ";
    cin >> c1.real >> c1.imag; // Вводим части первого числа

    cout << "Введите действительную и мнимую части второго "
         << "комплексного числа: ";
    cin >> c2.real >> c2.imag; // Вводим части второго числа

    Complex result = sum(c1, c2);
    // Вызываем вторую перегруженную функцию

    cout << "Сумма комплексных чисел: "
         << result.real;

    if (result.imag >= 0)
        cout << " + " << result.imag << "i";
    else
        cout << " - " << -result.imag << "i";

    cout << endl; // Переходим на новую строку

    return 0; // Завершаем программу
}

