
#include <iostream>  // Подключение библиотеки для ввода и вывода
#include <cstdlib>   // Подключение библиотеки случайных чисел
#include <ctime>     // Подключение библиотеки времени

using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian"); // Подключение русского языка

    int a[100]; // Объявление массива на 100 элементов
    int n;      // Количество элементов массива
    int k;      // Номер удаляемого элемента

    cout << "Введите количество элементов: ";
    cin >> n; // Ввод количества элементов

    srand(time(0)); // Инициализация генератора случайных чисел

    // Заполнение массива случайными числами
    for (int i = 0; i < n; i++)
    {
        a[i] = rand() % 21 - 10; // Числа от -10 до 10
    }

    // Вывод исходного массива
    cout << "Исходный массив: ";
    for (int i = 0; i < n; i++)
    {
        cout << a[i] << " ";
    }

    // Ввод номера удаляемого элемента
    cout << "\nВведите номер элемента для удаления: ";
    cin >> k;

    // Проверка правильности номера
    if (k < 1 || k > n)
    {
        cout << "Неверный номер элемента!";
        return 0;
    }

    // Удаление элемента сдвигом влево
    for (int i = k - 1; i < n - 1; i++)
    {
        a[i] = a[i + 1];
    }

    n--; // Уменьшение длины массива

    // Вставка нуля после каждого чётного элемента
    for (int i = 0; i < n; i++)
    {
        if (a[i] % 2 == 0)
        {
            // Сдвиг элементов вправо
            for (int j = n; j > i + 1; j--)
            {
                a[j] = a[j - 1];
            }

            a[i + 1] = 0; // Вставка нуля после чётного элемента
            n++;           // Увеличение длины массива

            i++; // Пропуск вставленного нуля
        }
    }
    // Вывод итогового массива
    cout << "\nИтоговый массив: ";
    for (int i = 0; i < n; i++)
    {
        cout << a[i] << " ";
    }
    return 0; // Завершение программы
}
