#include <iostream>  
#include <cmath>     
#include <iomanip>   // Подключение средств форматирования вывода
using namespace std; 
int main() 
{
    setlocale(LC_ALL, "Russian");
    double a = 0.1;       // Начальное значение аргумента
    double b = 0.8;       // Конечное значение аргумента
    int k = 10;           // Количество интервалов
    double h = (b - a) / k; // Вычисление шага изменения аргумента
    const int N = 35;     // Количество членов ряда
    const double eps = 0.0001; // Заданная точность
    const double pi = acos(-1.0); // Вычисление числа пи
    cout << "Вычисление функции" << endl; // Вывод заголовка
    cout << fixed << setprecision(8); // Вывод восьми знаков после запятой
    for (int i = 0; i <= k; i++) // Цикл по значениям аргумента
    {
        double x = a + i * h; // Вычисление текущего аргумента
        double SN = 0.0; // Начальное значение суммы первых N членов
        for (int n = 1; n <= N; n++) // Цикл суммирования 35 членов
        {
            double an = pow(x, n) * cos(n * pi / 3.0) / n;
            // Вычисление общего члена ряда

            SN += an; // Добавление члена к сумме SN
        }
        double SE = 0.0; // Начальное значение суммы с точностью eps
        int n = 1; // Номер текущего члена ряда
        double an = x * cos(pi / 3.0);
        // Вычисление первого члена ряда при n = 1
        while (fabs(an) >= eps) // Проверка условия продолжения суммирования
        {
            SE += an; // Добавление текущего члена к сумме SE
            n++; // Переход к следующему номеру члена
            an = pow(x, n) * cos(n * pi / 3.0) / n;
            // Вычисление следующего члена ряда
        }
        double Y = -0.5 * log(
            1.0 - 2.0 * x * cos(pi / 3.0) + x * x
        ); // Вычисление точного значения функции
        cout << "X = " << x; // Вывод текущего аргумента
        cout << "  SN = " << SN; // Вывод суммы первых 35 членов
        cout << "  SE = " << SE; // Вывод суммы с заданной точностью
        cout << "  Y = " << Y << endl; // Вывод точного значения
    }
    return 0; // Завершение программы
}
